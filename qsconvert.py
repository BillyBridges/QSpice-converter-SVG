def get_text_alignment(orientation_code, IsPin = False):
# Maps QSpice Orientation/Justification code to SVG attributes.
# Returns (anchor, baseline, rotation_deg)

    rotation_bits = (orientation_code >> 4) & 0x0F
    justification_bits = orientation_code & 0x0F
    if rotation_bits in ROTATION_MAP:
        rotation = ROTATION_MAP[rotation_bits]
    else:
        rotation = 0
    if justification_bits in JUSTIFICATION_MAP:
        anchor, baseline = JUSTIFICATION_MAP[justification_bits]
    else:
        if IsPin:
            anchor, baseline = HIDDEN, HIDDEN
        else:
            anchor, baseline = MIDDLE, MIDDLE
    if IsPin and (justification_bits == MIDDLE_MIDDLE):
        anchor, baseline = HIDDEN, HIDDEN

    return anchor, baseline, rotation, justification_bits, rotation_bits

