def hash_symbol_path(symbol):
    etype = symbol.get(TYPE)
    l = ['Symbol Path']
    pathcount = 0
    etype = None
    castable = symbol.get(CASTABLE, False)

    def _value(d, f_dict, aux, depth, k, parent):
        nonlocal etype
        if etype in ANNOTATION_DEFS:
            if k in ANNOTATION_DEFS[etype]:
                if (not castable) or (COLOR not in k):
                    if isinstance(d, (list, tuple)):
                        r = tuple(d)
                    else:
                        r = d
                    l.append(r)
        return 0

    def _dict(d, f_dict, aux, depth, k, parent):
        nonlocal etype, pathcount
        if isinstance(d, QSpice):
            etype = d.get(TYPE)
            if etype in ANNOTATION_DEFS:
                l.append("«")
                l.append(etype)
                pathcount += 1
                traverse(d, f_dict, aux, depth)
                l.append("»")
        else:
            etype = None
        
        return 0

    f_dict = {'value_fb': _value, 'dict_fb': _dict}
    p_rot = symbol[PARENT].get(ROTATION, 0)
    p_dns = combine_dnss(symbol.get(PARENT_DONOTSTUFF, []))
    l.extend([isdiagonal(p_rot), (0 if castable else p_dns)])
    traverse(symbol, f_dict, None)
    return tuple(l) if (pathcount > 0) else 0

def hash_symbol_pins(symbol):
    etype = symbol.get(TYPE)
    l = ['Symbol Pins']
    pincount = 0
    anchor = 0
    baseline = 0
    etype = None
    castable = symbol.get(CASTABLE, False)

    def _value(d, f_dict, aux, depth, k, parent):
        nonlocal pincount, anchor, baseline
        if etype in (PIN, PINLABEL):
            if k in SYMBOL_PIN_HASH_DEFS:
                if (not castable) or (COLOR not in k):
                    if isinstance(d, (list, tuple)):
                        r = tuple(d)
                    else:
                        r = d
                    l.append(r)
        return 0

    def _dict(d, f_dict, aux, depth, k, parent):
        nonlocal anchor, baseline, etype, pincount
        if isinstance(d, QSpice):
            etype = d.get(TYPE)
            if etype in (PIN, PINLABEL):
                has_netname = d.get(NETNAME) is not None
                l.append(has_netname)
                if (not has_netname):
                    anchor, baseline, rot, jb, rb = get_text_alignment(d.get(ORIENTATION,0), True)
                    if (HIDDEN not in (anchor, baseline)):
                        l.append("«")
                        pincount += 1
                        traverse(d, f_dict, aux, depth)
                        l.append("»")
        else:
            etype = None
        return 0

    f_dict = {'value_fb': _value, 'dict_fb': _dict}
    p_rot = symbol[PARENT].get(ROTATION, 0)
    if p_rot > 7:
        p_rot -= 8
        mirror = True
    else:
        mirror = False
    dns = combine_dnss(symbol.get(PARENT_DONOTSTUFF, []))
    l.extend([(p_rot in (DEG0, DEG45CCW, DEG90CCW, DEG45CW)),
         (p_rot in (DEG135CW, DEG135CCW, DEG90CW, DEG180)),
         isdiagonal(p_rot), mirror, (0 if castable else dns)])
    traverse(symbol, f_dict, None)
    return tuple(l) if (pincount > 0) else 0

def hash_symbol(symbol, target_key = None, target_collection_key = None):
    if target_key is not None:
        target_key[0] = SVG_HASH
    if target_collection_key is not None:
        target_collection_key[0] = SVG_SYMBOLS
    etype = symbol.get(TYPE)
    if etype == NET:
        net_name = dequote(str(symbol.get(NETNAME, ""))).upper()
        if net_name in (GND, CHASSIS, EARTH):
            return net_name
        else:
            return NETARROW
    elif etype in (JUNCTION, JUMPER):
        return JUNCTION
    elif etype == PIN:
        return etype
    hpath = hash_symbol_path(symbol)
    hpins = hash_symbol_pins(symbol)
    out = []
    if hpath: out.append(hpath)
    if hpins: out.append(hpins)
    if len(out) == 2:
        return tuple(out)
    elif hpath and (not hpins):
        return hpath
    elif hpins and (not hpath):
        return hpins

    return 0

def register_symbol(symbol, symbols, counter, mark_bounds=False):
    etype = symbol.get(TYPE)
    if etype not in (SYMBOL, NET, JUNCTION, PIN, JUMPER):
        return None
    if etype == NET:
        net_name = dequote(str(symbol.get(NETNAME, ""))).upper()
        if net_name == GND:
            symbol[SYMBOLNAME] = GND
            return register_symbol_path(symbol, counter)
        elif net_name == EARTH:
            symbol[SYMBOLNAME] = EARTH
            return register_symbol_path(symbol, counter)
        elif net_name == CHASSIS:
            symbol[SYMBOLNAME] = CHASSIS
            return register_symbol_path(symbol, counter)
        else:
            symbol[SYMBOLNAME] = NETARROW
            return register_symbol_path(symbol, counter)
    elif etype in (JUMPER, JUNCTION):
        symbol[SYMBOLNAME] = JUNCTION
        return register_symbol_path(symbol, counter)
    elif etype == PIN:
        symbol[SYMBOLNAME] = PIN
        return register_symbol_path(symbol, counter)
    _depth = symbol.get(DEPTH)
    out = QSpice({TYPE: etype, DEPTH: _depth})
    if PARENT in symbol:
        dns = combine_dnss(symbol.get(PARENT_DONOTSTUFF, []))
        diagonal = isdiagonal(symbol[PARENT].get(ROTATION, 0))
        sw_scale = TRQS2 if diagonal else 1
    else:
        dns = 0
        diagonal = False
        sw_scale = 1
    b = virgin_bounds()
    stype = f'symbol_{get_symbol_type(symbol)}'
    hpath = hash_symbol_path(symbol)
    hpins = hash_symbol_pins(symbol)
    if hpath:
        if hpath not in symbols:
            spath = register_symbol_path(symbol, counter, b, mark_bounds=mark_bounds)
        else:
            spath = symbols[hpath]
    if hpins:
        if hpins not in symbols:
            spins = register_symbol_pins(symbol, counter, b, mark_bounds=mark_bounds)
        else:
            spins = symbols[hpins]
    if hpath and hpins:
        out[DIAGONAL] = diagonal
        out[DONOTSTUFF] = dns
        out['scale'] = sw_scale    
        count(stype, counter)
        _id = f'{stype}_{counter[stype]}'
