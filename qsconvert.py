def process_image(el, counter, svg_paths, b, mark_bounds = False, show = True):
# Identify if this is an image container.
# Should only be called if el[TYPE] is RECT.
    image_data = el.get(EXTRA_10, None)

    if image_data:
        p1 = el.get(P1, (0, 0))
        p2 = el.get(P2, (0, 0))

        x = min(p1[0], p2[0]) * SCALE_FACTOR
        y = -max(p1[1], p2[1]) * SCALE_FACTOR
        w = abs(p1[0] - p2[0]) * SCALE_FACTOR
        h = abs(p1[1] - p2[1]) * SCALE_FACTOR
        if show:
            try:
                # Convert Hex to Bytes then to Base64
                raw_bytes = bytes.fromhex(image_data)

                # Ignores blend modes 0xa and 0x9 which are not supported by CSS
                # Due to CSS no being capable of inverting the background
                color = el.get(FILLCOLOR, 0)
                blend = (color >> 24) & 0xff
                filter_ = IMAGE_BLENDS.get(blend, '')
                if blend == 0xB:
                    # BMP header is usually 54 bytes.
                    # We only want to invert the color data, not the file structure.
                    header = raw_bytes[:54]
                    pixel_data = raw_bytes[54:]

                    # Invert pixels: 255 - value (for every byte in the pixel array)
                    inverted_pixels = bytes([255 - byte for byte in pixel_data])
                    raw_bytes = header + inverted_pixels

                b64_data = base64.b64encode(raw_bytes).decode('utf-8')

                count(IMAGE, counter)

                img_svg = (
                    f'<image x="{x}" y="{y}" width="{w}" height="{h}"{filter_} '
                    f'xlink:href="data:image/bmp;base64,{b64_data}" id="img_{counter[IMAGE]}" />'
                )
                svg_paths.append(img_svg)
            except Exception as e:
                print(f'The image processing failed: {e}')
        get_path_bounds([('_', (x, y, x+w, y+h))], b, svg_paths, mark_bounds, counter, _id = f'img_{counter[IMAGE]}')

def orient_pinlabel(rb, rot_code, anchor, baseline, rotation, mirror):
    # If the symbol rotation is > 90° in either direction (DEG135CW, DEG135CCW, DEG90CW, DEG180)
    if (rot_code in (DEG135CW, DEG135CCW, DEG90CW, DEG180)):
        if (not mirror):
            anchor = flip(anchor, END, START)
        rotation += 180
    else:
        if (mirror):
            anchor = flip(anchor, END, START)
    return anchor, baseline, rotation

def mirror_text(rb, rot_code, anchor, baseline, rotation):
# Handles the arbitrary, stupid, non-sensical and time-wasting flips
# that QSpice does when a component is mirrored.
    # Groups for clean set-lookup
    NO_FLIP_DIAG = {DEG135CW, DEG135CCW}
    RB_GROUP_0 = {DEG135CW, DEG45CW, DEG90CW, DEG135CCW, DEG45CCW}

    # --- Rule Set 1: Anchor & Baseline Flips ---
    if rb in (DEG0, DEG180) or rot_code in (DEG90CW, DEG45CCW, DEG45CW):
        if rot_code not in NO_FLIP_DIAG:
            anchor = flip(anchor, END, START)

    elif rb == DEG90CCW:
        if rot_code not in NO_FLIP_DIAG:
            baseline = flip(baseline, ALPHABETIC, HANGING)

    if rot_code == DEG0:
        if rb in RB_GROUP_0:
            anchor = flip(anchor, END, START)
        if rb == DEG90CW:
            anchor = flip(anchor, END, START)
            baseline = flip(baseline, ALPHABETIC, HANGING)

    # --- Rule Set 2: Rotation Adjustments ---
    if rot_code == DEG45CW:
        if rb == DEG135CCW:
            rotation = 180
        elif rb in (DEG90CW, DEG135CW, DEG180, DEG45CW):
            rotation -= 45

    if rot_code in (DEG90CW, DEG135CCW, DEG135CW):
        rotation += 180

    return anchor, baseline, rotation

def get_text_svg(transform, font, fontsize, color, anchor, baseline, id_, safe_lines, depth, counter, b, fs, crv = None, aprin = None, ispin = None, remove_fill = False, castable = False, invisible = False):
    Push([])
    sls = [safe_lines] if isinstance(safe_lines[0], str) else safe_lines
    gopen = False
    for line in sls:
        if line[4]: # annoying lines over characters
            notpos = line[4]
            gopen = True
            for i in notpos:
                path_data = get_char_overline(line[0], i, anchor, baseline, FONT, fs, line[2], line[3])
                push(QSpice({TYPE: PATH, P1: (0, 0), PATHDATA: path_data, STROKEWIDTH: (NOT_STROKE_WIDTH*fs)/160, LINETYPE: 0, LINECOLOR: color, FILLCOLOR: -1}))
    
    if len(sls) > 1:
        tspans_l = []
        for sl in sls:
            tspans_l.append(f'<tspan x="{rpub(sl[2])}" y="{rpub(sl[3])}">{sl[1]}</tspan>')
        tspans = ''.join(tspans_l)
        xy = ''
    else:
        xy = f' x="{rpub(sls[0][2])}" y="{rpub(sls[0][3])}"'
        tspans = sls[0][1]
    if invisible: color = None
    fill_str = '' if (remove_fill or castable) else f' fill="{pub_color(color)}"'
    text_svg = (
        f'<text{xy}{"" if gopen else transform} font-family="{font}" font-size="{rpub(fontsize)}"'
        f'{fill_str} text-anchor="{anchor}" dominant-baseline="{baseline}" '
        f'xml:space="preserve" id="{f"{id_}_t" if gopen else id_}">{tspans}</text>'
    )
    
    out = []
    if gopen:
        out.append(f'<g id="{id_}_g"{transform}>')
    out.append(text_svg)
    while stack():
        draw_fundamental(pop(), None, out, counter, b, None, None, mark_bounds=MARK_BOUNDS, transform = None if gopen else transform, bound_transform = transform if gopen else None)
    if gopen:
        out.append('</g>')
    Pop()
    return "\n".join(out)
    
