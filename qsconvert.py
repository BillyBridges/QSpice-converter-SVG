def get_net_angle(el, wire_endpoints, elements):
    _p_p1 = el.get(P1, (0, 0))
    sums = wire_endpoints.get(_p_p1)
    angle = 0
    if sums:
        sum_x, sum_y, count = sums
        if detect_straight_line(sums):
            # Clean Normalization Step:
            for el_wire in elements:
                if isinstance(el_wire, QSpice) and el_wire.get(TYPE) == WIRE:
                    if _p_p1 in (el_wire[P1], el_wire[P2]):
                        dx, dy = el_wire[P2][0] - el_wire[P1][0], el_wire[P2][1] - el_wire[P1][1]
                        angle = degrees(atan2(dx, dy)) + 90
                        break
        else:
            angle = degrees(atan2(sum_x, sum_y))
    el[ANGLE] = angle
    return angle

def process_net_name(el, counter, net_name, svg_paths, b, show=True, mark_bounds = False):
    if (dequote(net_name).upper() not in (GND, EARTH, CHASSIS)):
        el[ISCOMMENTORVISIBLE] = 1
        readability_angle = 0
        push_x = 0
        push_y = 0
        anchor = MIDDLE
        fs = el.get(FONTSIZE, 1) * FONT_SCALE * SCALE_FACTOR
        color = NET_COLOR
        port_bg = ""
        # Use the existing calculated angle and position
        # This matches the logic used for the 'netarrow' path element
        p1 = el.get(P1, (0, 0))
        is_port = el.get(ISPORT, False)
        angle_deg = el.get(ANGLE, 0) + 90
        tx, ty = tr(p1)
        if el.get(ONWIREEND, False):
            # Normalize the text rotation for readability [-90, 90]
            # We must track if we flipped the text to adjust the anchor/offset
            readability_angle = angle_deg
            is_flipped = False
            if readability_angle > 90:
                readability_angle -= 180
                is_flipped = True
            elif readability_angle < -90:
                readability_angle += 180
                is_flipped = True

            # Alignment and "Push" to the tip
            # The netarrow symbol is 80 units long.
            # We push the text NET_TEXT_X_OFFSET past that.
            tip_offset = ((80 + NET_TEXT_X_OFFSET_ABSOLUTE) * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (NET_TEXT_X_OFFSET_RELATIVE * fs)

            if is_flipped:
                # If we rotated the text 180 deg to keep it upright,
                # the local X axis is now pointing BACKWARD toward the wire.
                # We use END anchor and a negative offset to stay at the tip.
                anchor = END
                push_x = -tip_offset
            else:
                anchor = START
                push_x = tip_offset
            dbl = CENTRAL
            push_y = (NET_TEXT_Y_OFFSET_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (NET_TEXT_Y_OFFSET_RELATIVE * fs)
        else:
            # Normalize angle to range [-90, 90] for readability
            readability_angle = angle_deg - 90
            if readability_angle > 90:
                readability_angle -= 180
            elif readability_angle < -90:
                readability_angle += 180

            anchor = MIDDLE
            dbl = ALPHABETIC
            push_y = (PERPENDICULAR_NET_TEXT_Y_OFFSET_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (PERPENDICULAR_NET_TEXT_Y_OFFSET_RELATIVE * fs)
            push_x = (PERPENDICULAR_NET_TEXT_X_OFFSET_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (PERPENDICULAR_NET_TEXT_X_OFFSET_RELATIVE * fs)
            if is_port:
                push_y += (PORT_PERPENDICULAR_NET_TEXT_Y_OFFSET_RELATIVE * fs) + (PORT_PERPENDICULAR_NET_TEXT_Y_OFFSET_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE)

        # Generate the element
        # The order of transform matters: Move to P1 -> Rotate -> Move to Tip
        # Transform here only allow nets on the shallowest level
        _transform = []
        _transform.append((TRANSLATE, tx, ty))
        _transform.append((ROTATE, readability_angle))
        _transform.append((TRANSLATE, push_x, push_y))
        s_tr, t_, t_matrix = simplify_transforms(_transform)
        transform = get_transform_string(s_tr, t_matrix)

        # Calculate dimensions
        text_data = parse_single_line(net_name)
        rx, ry, _rx, _ry = get_text_corners(text_data[0], FONT, fs, anchor, dbl)
        rx -= (PORT_PADDING_X_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (PORT_PADDING_X_RELATIVE * fs) - (PORT_OFFSET_X_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) - (PORT_OFFSET_X_RELATIVE * fs)
        _rx +=(PORT_PADDING_X_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (PORT_PADDING_X_RELATIVE * fs) + (PORT_OFFSET_X_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (PORT_OFFSET_X_RELATIVE * fs)
        ry -= (PORT_PADDING_Y_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (PORT_PADDING_Y_RELATIVE * fs) - (PORT_OFFSET_Y_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) - (PORT_OFFSET_Y_RELATIVE * fs)
        _ry +=(PORT_PADDING_Y_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (PORT_PADDING_Y_RELATIVE * fs) + (PORT_OFFSET_Y_ABSOLUTE * SCALE_FACTOR * NATIVE_SYMBOL_SCALE) + (PORT_OFFSET_Y_RELATIVE * fs)
        path_data = rect_(rx, ry, _rx, _ry)
        baked_data = apply_transform(path_data, _transform)

        portbg = None
        if is_port and (svg_paths is not None):
            portbg = process_path(baked_data, svg_paths, PORTBG, el, 0, DEG0, 0, counter, b, show=show, _transform = [])

        count(NETTEXT, counter)
        id_ = f'nettext_{counter[NETTEXT]}'
        if (b is not None):
            get_path_bounds(baked_data, b, svg_paths, mark_bounds, counter, PORT_SW * NATIVE_SYMBOL_SCALE * SCALE_FACTOR, id_)
        text_elem = get_text_svg(transform, FONT, fs, color, anchor, dbl, id_, text_data, 1, counter, b, fs)
        if show and (svg_paths is not None):
            svg_paths.append(text_elem)
        return {DRAWABLEID: True, 'cmd': TEXT, 'dtype': NETTEXT, 'Font': FONT, FONTSIZE: fs, FONTCOLOR: color, TRANSFORM: s_tr, 'transform_d': t_, 'anchor': anchor, 'dominant_baseline': dbl, 'id': id_, STRG: text_data[0], 'svg': text_elem, 'portbg': portbg}

def get_transform(el, p = None, rot = None, mirror = None, angle = None, scale = None):
    if not el:
        return []

    _transform = []
    if p is None:
        p = el.get(P1, (0, 0))
    if rot is None:
        rot = el.get(ROTATION, 0)

    # 1. Evaluate mirroring and extract base angle
    if mirror is None:
        mirror = ismirror(rot)
    if mirror:
        rot = demirror(rot)
    if angle is None:
        angle = el.get(ANGLE, ROTATION_MAP.get(rot, 0))

    # 2. TRANSLATE MUST BE FIRST
    # This anchors the global origin to the correct canvas coordinates
    # BEFORE any mirroring or rotation twists the coordinate system.
    if rtup(p) != (0, 0):
        tx, ty = tr(p)
        _transform.append((TRANSLATE, tx, ty))

    # 3. MIRROR AND ROTATE ORDER
    # In graphics stacks, operations apply to the geometry in reverse order
    # of how they are listed. Placing SCALE before ROTATE means the raw
    # paths will be Rotated first, and THEN Mirrored.
    if mirror:
        _transform.append((SCALE, -1, 1))

    if angle:
        _transform.append((ROTATE, angle))

    # Uniform scale can safely go at the end, as it scales X and Y equally
    if isdiagonal(rot):
        _transform.append((SCALE, SQRT2, SQRT2))
    if scale is not None:
        _transform.append((SCALE, scale, scale))

    return _transform

def get_path_transform(etype, el, p_p1, p_rot,
    # localize names:
    PIN = q.PIN, 
    PINLABEL = q.PINLABEL, 
    tr = q.tr, 
    TRANSLATE = q.TRANSLATE, 
    SCALE = q.SCALE, 
    len = len, 
    range = range, 
    max = max, 
    ROTATION_MAP = q.ROTATION_MAP, 
    ROTATE = q.ROTATE, 
    isdiagonal = q.isdiagonal, 
    demirror = q.demirror, 
    NET = q.NET, 
    SQRT2 = q.SQRT2, 
    ANGLE = q.ANGLE,
    combine_rotations = q.combine_rotations
):
    _transform = []
    if p_p1 and etype not in (PIN, PINLABEL):
        _p_rot = combine_rotations(p_rot)
        for i in range(max(len(p_p1), len(p_rot))):
            if i < len(p_p1):
                tx, ty = tr(p_p1[i])
                _transform.append((TRANSLATE, tx, ty))
            if i < len(p_rot):
                rot_code = p_rot[i]
                if p_rot[i] >= 8:
                    _transform.append((SCALE, -1, 1))
                    rot_code -= 8
                angle = ROTATION_MAP.get(rot_code, 0)
 
                _transform.append((ROTATE, angle))
        if (isdiagonal(demirror(_p_rot))) and (etype != NET):
            _transform.append((SCALE, SQRT2))
    angle = el.get(ANGLE)
    if angle:
        _transform.append((ROTATE, angle))
    return _transform

