def generate_random_orientation():
# Constructs a random orientation code compatible with get_text_alignment:
# orientation_code = (rotation_bits << 4) | justification_bits

    j_bits = random.choice(VALID_JUSTIFICATIONS)
    r_bits = random.choice(VALID_ROTATIONS)

    # Combine according to (orientation_code >> 4) & 0x0F logic
    return (r_bits << 4) | j_bits

def dimensions(b):
    global WIDTHCM
    global HEIGHTCM

    min_x = b[MIN_X]
    min_y = b[MIN_Y]
    max_x = b[MAX_X]
    max_y = b[MAX_Y]

    # Dimensions not padded:
    canvas_width = abs(max_x - min_x)
    canvas_height = abs(max_y - min_y)

    cm = min(canvas_width, canvas_height) * CANVAS_PADDING
    min_x -= cm
    min_y -= cm
    max_x += cm
    max_y += cm

    # Dimensions padded:
    canvas_width = abs(max_x - min_x)
    canvas_height = abs(max_y - min_y)

    # Adjust the destination dimensions to fit the parameters:
    # Uses the dimension or resolution informed, and when 2 dimensions
    # are informed, fits the drawing inside and trims excess width or height.
    aspect = canvas_width / (canvas_height + epsilon)
    if dimv == 4: # Sets dimensions to fit informed resolution
        WIDTHCM = canvas_width / UNITSPERCM
        HEIGHTCM = canvas_height / UNITSPERCM
    elif dimv == 2: # Sets width to conform to informed height
        WIDTHCM = HEIGHTCM * aspect
    elif dimv == 1: # Sets height to conform to informed width
        HEIGHTCM = WIDTHCM / aspect
    elif dimv == 0: # Sets dimensions to A3 size
        portrait = canvas_height > canvas_width
        if portrait:
            WIDTHCM = 29.7
            HEIGHTCM = 42
        else:
            WIDTHCM = 42
            HEIGHTCM = 29.7

    # Trims excess width or height from destination:
    dest_aspect = WIDTHCM / HEIGHTCM
    if (aspect / dest_aspect) > 1: # Origin wider than destination
        HEIGHTCM = WIDTHCM / aspect
    else: # Origin taller than destination
        WIDTHCM = HEIGHTCM * aspect
    return canvas_width, canvas_height, cm

def load_font(defs):
    # 1. Read the font file from current folder and encode it to Base64
    formats = ('.woff2', '.woff', '.ttf', '.otf' )
    formats2 = ('woff2', 'woff', 'ttf', 'otf' )
    foundfont = False
    for i in range(len(formats)):
        fn = f'{FONT}{formats[i]}'
        format_ = formats2[i]
        if os.path.isfile(fn):
            with open(fn, "rb") as font_file:
                encoded_font = base64.b64encode(font_file.read()).decode('utf-8')
            foundfont = True
            break

    # 2. Build the font embedding style header
    if foundfont:
        defs.append(
f"""<style type="text/css">
@font-face {{
    font-family: "{FONT}";
    src: url("data:font/{format_};base64,{encoded_font}") format("{format_}");
    font-weight: normal;
    font-style: normal;
}}
</style>""")

