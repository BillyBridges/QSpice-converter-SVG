def process_text(etype, el, counter, svg_paths, b, show = True, mark_bounds = False, use_transform = None, abstract = False, remove_fill = False, p_p1 = None, p_dns = None, p_rot = None):
# Process the position and appearence of text elements, except net names
    raw_text = el.get(STRG) if (etype in (TEXT, 'net_desc')) else (el.get(PINNAME) if (etype in (PIN, PINLABEL)) else el.get(NETNAME))

    if not raw_text: 
        return CONTINUE
    invisible = False
    # Check visibility (IsCommentOrVisible)
    # 0=Visible, 1=Comment, 2=Invisible, 3=Invisible Comment
    vis = int(el.get(ISCOMMENTORVISIBLE, 0))
    if vis >= 2 and (not is_symbol): 
        invisible = True
    
    ptype = None
    parent = el.get(PARENT)
    if isinstance(parent, QSpice):
        ptype = parent.get(TYPE)

    depth = el.get(DEPTH, 0)
    if (vis == 0) and (depth <= 2) and HIDE_SPICE and (not is_symbol) and (not abstract):
        invisible = True

    castable = el.get(CASTABLE, False)
    crv = False
    aprin = False
    stype = get_symbol_type(el)
    insname = get_instance_name(el)
    if CENTER_RESISTOR_VALUE and (stype.upper() == 'R') and (not is_symbol):
        if (el == get_component_value_object(el)):
            crv = True

    if AUTOPLACE_RESISTOR_INSTANCE_NAME and (stype.upper() == 'R') and (not is_symbol):
        if (el == get_instance_name_object(el)):
            aprin = True
    if aprin and crv: print('"process_text" warning: Abnormal component properties: Instance name and Value collision.')

    # Pins connected through net name don't show:
    ispin = etype in (PIN, PINLABEL)
    if ispin:
        if el.get(NETNAME):
            return CONTINUE
        etype = PINLABEL

    if p_rot is None: p_rot = el.get(PARENT_ROTATION, [])

    p_rot_ = p_rot
    _p_rot = combine_rotations(p_rot_)

    p1 = el.get(P1, (0, 0))
    lp1 = el.get(LP1, (0, 0))
    if p_p1 is None: p_p1 = el.get(PARENT_P1, [])
    if p_dns is None: p_dns = el.get(PARENT_DONOTSTUFF, [])
    _p_dns = combine_dnss(p_dns)
    _x, _y = tr(p1)
    px, py = tr(lp1)
    p_p1_ = tr(p_p1)

    orient = int(el.get(ORIENTATION, 0))
    anchor, baseline, rotation, jb, rb = get_text_alignment(orient, ispin)
    if HIDDEN in (baseline, anchor): 
        return CONTINUE

    color = el.get(FONTCOLOR, 0x1000000)
 
    if (hex_to_int(color) > 0xFFFFFF):
        if vis == 0:
            color = get_color(COMPONENT_ATT_COLOR, _p_dns) if ptype == SYMBOL else get_color(SPICE_STATEMENT_COLOR, _p_dns)
        elif vis == 1:
            color = get_color(COMPONENT_COMMENT_COLOR, _p_dns) if ptype == SYMBOL else get_color(COMMENT_COLOR, _p_dns)
        elif vis == 2:
            color = get_color(DONOTSTUFF_COLOR, 1)
    else:
        color = get_color(color, _p_dns)
        
    fs = el.get(FONTSIZE, 1) * FONT_SCALE * SCALE_FACTOR
    if crv and (not is_symbol):
        fs *= RESISTOR_CENTER_VALUE_FONT_RESCALE
    if aprin and (not is_symbol):
        fs *= RESISTOR_INSTANCE_NAME_FONT_RESCALE

    mirror = False
    rot_code = _p_rot
    if _p_rot >= 8:
        mirror = True
        rot_code -= 8

    angle = [ROTATION_MAP.get(demirror(i), 0) for i in p_rot_]

    diagonal = isdiagonal(rot_code)

    if diagonal and (not abstract) and (not is_symbol):
        _x *= SQRT2
        _y *= SQRT2
        px *= SQRT2
        py *= SQRT2

    safe_lines = parse_str(raw_text, fs)
    if run_translate_text:
        safe_lines = translate_text(safe_lines, raw_text, abstract, fs, etype, el, vis, ispin, stype, ptype, insname, invisible, depth, color, mirror, crv, aprin, angle, diagonal, anchor, baseline, rotation)
    _i = len(safe_lines)
    lines = [item[0] for item in safe_lines]
    isbrand = ((depth > 2) or is_symbol) and (len(safe_lines) == 1) and (safe_lines[0][0] == 'Qorvo') and (vis > 0) and (not ispin)
    if ispin:
        anchor, baseline, rotation = orient_pinlabel(rb, rot_code, anchor, baseline, rotation, mirror)
    else:
        if mirror:
            anchor, baseline, rotation = mirror_text(rb, rot_code, anchor, baseline, rotation)

    dfactor = 1
    if (crv or aprin) and (not is_symbol):
        anchor =  MIDDLE
        baseline = MIDDLE if crv else ALPHABETIC
        rotation = orient = 0
        s_bounds = get_resistor_rect(el)
        if not s_bounds:
            s_bounds = get_raw_symbol_bounds(el)
        p1 = get_rect_center(*s_bounds)
        _x, _y = tr(p1)
        if diagonal and (not abstract):
            _x *= SQRT2
