def grow_file(filename, file_content, qtr, bg, embed_font, paths, virgin_obj, obj, b, canvas_width, canvas_height, canvas_padding): # A task
    # Opens a QSpice schematic or symbol, multiply all distances by the
    # growth factor "GROW" and saves as the same format to the working folder.
    # This is for when you want a smaller grid size on QSpice. The native symbols
    # can be grown when generating the SVG by parameter NATIVE_SYMBOL_SCALE(/NSS).
    # Taps are a problem, though, as QSpice shrinks them back when you open the
    # file, so beware of that.
    def grow(d):
        for key in d:
            if isinstance(d[key], QSpice):
                if (key != PARENT): grow(d[key])
            else:
                if ('Size' in key) or ('Width' in key) or (key in (P1, P2, P3, P4, LP1)):
                    if isinstance(d[key], list):
                        for i in range(len(d[key])):
                            d[key][i] *= GROW
                    elif isinstance(d[key], tuple):
                        d[key] = u_scale(d[key], GROW)
                    else:
                        d[key] *= GROW

    grow(virgin_obj)
    l = compose_qspice(virgin_obj)
    q = '\n'.join(l)
    name, ext = os.path.splitext(filename)
    dest = f'{name}(grown){ext}'
    if (not OVERWRITE):
        dest = str(get_unique_filename(dest))
    else:
        dest = str(get_unique_filename_from_list(dest, saved_files))
    with open(dest, 'w', encoding='cp1252', newline='\n') as out:
        out.write(q)
        saved_files.append(dest)
    print(f'Exported "{dest}"')

